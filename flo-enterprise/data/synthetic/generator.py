def _default(o):
    if isinstance(o, (date, datetime)):
        return o.isoformat()
    if isinstance(o, Decimal):
        return str(o)
    raise TypeError(type(o))


def manifest(data: dict[str, list[dict]]) -> dict:
    tables = {}
    for name, rows in sorted(data.items()):
        blob = json.dumps(rows, default=_default, sort_keys=True, ensure_ascii=False).encode()
        tables[name] = {"rows": len(rows), "sha256": hashlib.sha256(blob).hexdigest()}
    return {"seed": SEED, "label": SYNTHETIC_LABEL, "as_of": AS_OF.isoformat(),
            "period": [MONTHS[0].isoformat(), MONTHS[-1].isoformat()], "currency": "CAD", "tables": tables}


