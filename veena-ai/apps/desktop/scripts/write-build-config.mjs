// Writes electron/build-config.ts from VEENA_BILLING_URL / VEENA_INSIGHTS_URL (CI sets them).
// Only https:// URLs are accepted; anything else is written as "" (feature disabled).
import fs from "node:fs";
import path from "node:path";
const ok = (u) => (/^https:\/\/[A-Za-z0-9.-]+(\/[A-Za-z0-9._-]*)*$/.test(u || "") ? u.replace(/\/$/, "") : "");
const billing = ok(process.env.VEENA_BILLING_URL), insights = ok(process.env.VEENA_INSIGHTS_URL);
const out = path.resolve(import.meta.dirname, "../electron/build-config.ts");
fs.writeFileSync(out, `// Generated by scripts/write-build-config.mjs at build time.\nexport const BILLING_URL = ${JSON.stringify(billing)};\nexport const INSIGHTS_URL = ${JSON.stringify(insights)};\n`);
console.log(`build config: billing ${billing ? billing : "disabled"}, statistics ${insights ? insights : "disabled"}`);
