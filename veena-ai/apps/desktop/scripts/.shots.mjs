import { _electron as electron } from "@playwright/test";
import fs from "node:fs";
const ud = fs.mkdtempSync("/tmp/claude-0/ud-");
const app = await electron.launch({ args: [".", "--no-sandbox"], cwd: process.cwd(), env: { ...process.env, VEENA_USER_DATA: ud } });
const page = await app.firstWindow();
page.on("dialog", (d) => d.accept());
await page.waitForSelector("text=Welcome to VEENA", { timeout: 60000 });
const info = await page.evaluate(() => window.veena.backendInfo());
await fetch(info.url + "/api/settings", { method: "PATCH", headers: { Authorization: "Bearer " + info.token, "Content-Type": "application/json" }, body: JSON.stringify({ onboarded: true, text_model: "qwen2.5:1.5b", vision_model: "qwen2.5vl:3b", profile: "balanced" }) });
await page.reload();
await page.waitForSelector("text=Recent sessions");
await page.screenshot({ path: "/tmp/claude-0/shots/1-welcome.png" });
await page.getByLabel("Message").fill("Explain the difference between a process and a thread, with a short Python example.");
await page.keyboard.press("Enter");
await page.waitForSelector("button:has-text('Send')", { timeout: 180000 });
await page.waitForTimeout(1500);
await page.screenshot({ path: "/tmp/claude-0/shots/2-workspace.png" });
await page.getByRole("button", { name: "Screen Intelligence" }).first().click();
await page.getByRole("button", { name: "Choose screen or window" }).click();
await page.waitForTimeout(1500);
await page.screenshot({ path: "/tmp/claude-0/shots/3-picker.png" });
await page.locator("button[aria-pressed]").first().click();
await page.getByRole("button", { name: "Share", exact: true }).click();
await page.waitForTimeout(2500);
await page.screenshot({ path: "/tmp/claude-0/shots/4-screen.png" });
await page.getByRole("button", { name: "Stop Sharing", exact: true }).click();
for (const [name, file] of [["Interview Practice", "5-interview"], ["Knowledge", "6-knowledge"], ["Analytics", "7-analytics"], ["Meeting Copilot", "8-meeting"]]) {
  await page.getByRole("button", { name }).first().click();
  await page.waitForTimeout(1200);
  await page.screenshot({ path: `/tmp/claude-0/shots/${file}.png` });
}
await page.getByRole("button", { name: "Settings" }).first().click();
await page.waitForTimeout(1500);
await page.screenshot({ path: "/tmp/claude-0/shots/9-settings.png" });
await app.close();
