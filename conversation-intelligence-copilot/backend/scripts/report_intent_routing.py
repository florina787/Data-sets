"""Render docs/evaluation/INTENT_ROUTING_RESULTS.md from data/manifests/intent_routing/*.json (no re-evaluation)."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "data" / "manifests" / "intent_routing"
OUT = ROOT / "docs" / "evaluation" / "INTENT_ROUTING_RESULTS.md"
NAMES = {
    "rules_v1": "Rules only (before)", "qwen_only_v1": "Local Qwen only, old prompt (before)", "rules_first_v1": "Rules-first hybrid (previous router)",
    "rules_v2": "Rules only (after)", "qwen_only_v2_1": "Local Qwen only, prompt 2.1", "router_v2_no_llm": "Confidence router, no model",
    "router_v2": "Confidence router + local Qwen (final)",
}
ORDER = ["rules_v1", "qwen_only_v1", "rules_first_v1", "rules_v2", "qwen_only_v2_1", "router_v2_no_llm", "router_v2"]


def load(split: str, method: str, tag: str = "") -> dict | None:
    f = RES / f"{split}_{method}{tag}.json"
    return json.loads(f.read_text()) if f.exists() else None


def pct(x) -> str:
    return "—" if x is None else f"{x:.1%}"


def main() -> None:
    manifest = json.loads((ROOT / "backend" / "tests" / "evaluation" / "datasets" / "intent_benchmark_manifest.json").read_text())
    L = ["# Intent routing: results", "",
         "Generated by `backend/scripts/report_intent_routing.py` from `data/manifests/intent_routing/`. Method and protocol: "
         "[INTENT_ROUTING.md](INTENT_ROUTING.md).", "",
         f"Benchmark v2: {manifest['n']} questions in {manifest['families']} paraphrase families. "
         + ", ".join(f"{s} {m['n']} ({m['families']} families)" for s, m in manifest["splits"].items())
         + f". Test SHA-256 `{manifest['splits']['test']['sha256'][:16]}…`.", "",
         "## Held-out test split (scored once, after freezing at commit 24e7d7a)", "",
         "| Method | Accuracy | Macro F1 | Misrouted | Clarified | Unsupported rejected | False refusals | LLM invoked | p50 / p95 latency |",
         "|---|---|---|---|---|---|---|---|---|"]
    for m in ORDER:
        r = load("test", m, "_final")
        if r:
            L.append(f"| {NAMES[m]} | **{pct(r['accuracy'])}** | {r['macro_f1']:.3f} | {pct(r['misrouting_rate'])} | {pct(r['clarification_rate'])} | "
                     f"{pct(r['unsupported_rejection_rate'])} | {pct(r['false_refusal_rate'])} | {pct(r['llm_invocation_rate'])} | "
                     f"{r['latency_ms']['p50']:.0f} / {r['latency_ms']['p95']:.0f} ms |")
    L += ["", "Latency is wall-clock per question on 4 CPU cores. Qwen calls reuse llama.cpp's cached system-prompt prefix, so "
          "warm calls take about a second; the first call after start-up (model load + full prompt) took 8.7 s in an idle process, and 30–55 s while other jobs competed for the CPU.", ""]
    final = load("test", "router_v2", "_final")
    if final:
        L += ["### Coverage vs accuracy (final router, test)", "",
              f"* Answered (did not ask to clarify): {pct(final['coverage'])} of questions; accuracy when answered {pct(final['accuracy_when_answered'])}.",
              f"* Outcomes: {final['outcomes']}.", f"* Routing method used: {final['by_method']}.",
              f"* By question kind: {final['by_kind']}.", "",
              "### Per-intent (final router, test)", "", "| Intent | Precision | Recall | F1 | Support |", "|---|---|---|---|---|"]
        L += [f"| {x['intent']} | {x['precision']:.2f} | {x['recall']:.2f} | {x['f1']:.2f} | {x['support']} |" for x in final["per_intent"]]
        labs, mat = final["confusion"]["labels"], final["confusion"]["matrix"]
        short = {lab: "".join(w[0] for w in lab.split("_")).upper() for lab in labs}
        clash = {v for v in short.values() if list(short.values()).count(v) > 1}
        short = {lab: (v if v not in clash else (lab.split("_")[0][0] + lab.split("_")[-1][:3]).upper()) for lab, v in short.items()}
        L += ["", "### Confusion matrix (final router, test; rows = expected, columns = predicted)", "",
              "Abbreviations: " + ", ".join(f"{short[x]} = {x}" for x in labs), "",
              "| | " + " | ".join(short[x] for x in labs) + " |", "|---" * (len(labs) + 1) + "|"]
        L += [f"| **{short[labs[i]]}** | " + " | ".join(str(v) if v else "·" for v in row) + " |" for i, row in enumerate(mat)]
        L += ["", "Strict macro F1 counts a multi-intent question's secondary intent as an error; accuracy accepts it (see `acceptable`).", "",
              "### Remaining test errors (not fixed: the test split is not used for tuning)", "",
              "| Question | Expected | Predicted | Method |", "|---|---|---|---|"]
        L += [f"| {e['question']} | {e['expected']} | {e['predicted']} | {e['method']} |" for e in final["errors"]]
    L += ["", "## Validation split (used for prompt and threshold selection — optimistic)", "",
          "| Method | Accuracy | Macro F1 | Misrouted | LLM invoked |", "|---|---|---|---|---|"]
    for m in ORDER:
        r = load("validation", m)
        if r:
            L.append(f"| {NAMES[m]} | {pct(r['accuracy'])} | {r['macro_f1']:.3f} | {pct(r['misrouting_rate'])} | {pct(r['llm_invocation_rate'])} |")
    for m, label in (("qwen_only_v2_0", "Local Qwen only, prompt 2.0 (not selected)"),):
        r = load("validation", m)
        if r:
            L.append(f"| {label} | {pct(r['accuracy'])} | {r['macro_f1']:.3f} | {pct(r['misrouting_rate'])} | {pct(r['llm_invocation_rate'])} |")
    L += ["", "The v2 rules were written while reading train *and* validation errors, so validation scores for rules-based methods are "
          "not an unbiased estimate; the test table is.", ""]
    cfg = json.loads((ROOT / "backend" / "app" / "agents" / "data" / "intent_router_config.json").read_text())
    L += ["## Semantic stage calibration", "", f"`{json.dumps(cfg)}`", ""]
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
