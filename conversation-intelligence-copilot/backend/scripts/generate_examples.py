"""Run sample requests against the real dataset and save requests/outputs under examples/.

Usage (from backend/):  uv run python -m scripts.generate_examples
"""

from __future__ import annotations

import json
import os
import tempfile
from pathlib import Path

_tmp = Path(tempfile.mkdtemp(prefix="cic-examples-"))
os.environ.setdefault("MEMORY_DATABASE_PATH", str(_tmp / "memory.sqlite"))
os.environ.setdefault("CHECKPOINT_DATABASE_PATH", str(_tmp / "checkpoints.sqlite"))

from fastapi.testclient import TestClient  # noqa: E402

from app.config import PROJECT_ROOT  # noqa: E402
from app.main import app  # noqa: E402

SESSIONS = [
    ("01_q1_negative_topics", [
        {"question": "What were the top 5 topics most associated with negative customer sentiment in the last month represented in the dataset?"},
        {"question": "Compare the top two topics."},
        {"question": "What about the previous month?"},
    ]),
    ("02_q2_agent_coaching", [{"question": "Which support agents may benefit from additional coaching on empathy or customer communication, and what evidence supports that view?"}]),
    ("03_q3_sentiment_trajectory", [{"question": "How did customer sentiment change over the course of a selected conversation?", "selected_conversation_id": "C0000479"}]),
    ("04_q4_leadership_priorities", [
        {"question": "Which recurring customer concerns should contact-centre leadership review first?"},
        {"question": "Why was this concern ranked first?"},
        {"question": "Which findings are uncertain?"},
    ]),
    ("05_bonus_retrieval", [{"question": "Find conversations where the customer asked to escalate an app crash."}]),
    ("06_unsupported", [{"question": "What is the revenue impact of these complaints?"}]),
]


def slim(r: dict) -> dict:
    """Keep everything an evaluator needs; trim long chart payloads to their first rows."""
    out = {k: v for k, v in r.items() if k not in ("charts", "graphs")}
    out["charts"] = [{**{k: v for k, v in c.items() if k != "data"}, "data_preview": c["data"][:6], "rows": len(c["data"])} for c in r["charts"]]
    out["graphs"] = [{"graph_id": g["graph_id"], "nodes": len(g["nodes"]), "edges": len(g["edges"])} for g in r["graphs"]]
    return out


def to_markdown(name: str, turns: list[tuple[dict, dict]]) -> str:
    lines = [f"# {name.replace('_', ' ')}", "", "Generated by `backend/scripts/generate_examples.py` against the real dataset.", ""]
    for req, r in turns:
        lines += [f"## Q: {req['question']}", "", f"**Status:** {r['status']} · **intent:** {r['plan']['category']} · **window:** {r['dataset_scope']['window']['label']} · "
                  f"**QA:** {r['quality_status']['status']} ({r['quality_status']['passed']}/{r['quality_status']['total']}) · **mode:** {r['model_metadata']['mode']} · "
                  f"**latency:** {r.get('latency_ms')} ms", "", f"**{r['headline']}**", "", r["answer"], ""]
        if r["plan"]["notes"]:
            lines += ["Plan notes: " + " · ".join(r["plan"]["notes"]), ""]
        if r["key_points"]:
            lines += ["Key points:", ""] + [f"* {k}" for k in r["key_points"]] + [""]
        if r["recommendations"]:
            lines += ["Recommendations:", ""] + [f"* **{x['priority']} · {x['concern']}** — {x['suggested_action']} Owner: {x['decision_owner']}. Evidence: {', '.join(x['evidence'])}" for x in r["recommendations"]] + [""]
        if r["evidence"]:
            lines += ["Evidence:", ""]
            for e in r["evidence"][:4]:
                ex = " / ".join(f"[{x['role'][0].upper()}{x['turn_index']}] {x['text']}" for x in e["excerpts"][:3])
                lines.append(f"* `{e['conversation_id']}` ({e['topic']}, {e['sentiment']}) — {e['reason']}: {ex}")
            lines.append("")
        if r["uncertainty_notes"]:
            lines += ["Uncertainty:", ""] + [f"* {u}" for u in r["uncertainty_notes"]] + [""]
        lines += ["Charts: " + ", ".join(c["chart_id"] for c in r["charts"]), "", "---", ""]
    return "\n".join(lines)


def main() -> None:
    req_dir, out_dir = PROJECT_ROOT / "examples" / "requests", PROJECT_ROOT / "examples" / "outputs"
    req_dir.mkdir(parents=True, exist_ok=True)
    out_dir.mkdir(parents=True, exist_ok=True)
    with TestClient(app) as client:
        for name, reqs in SESSIONS:
            sid, turns = None, []
            for req in reqs:
                r = client.post("/api/chat", json={**req, "session_id": sid}).json()
                sid = r["session_id"]
                turns.append((req, r))
            (req_dir / f"{name}.json").write_text(json.dumps([{**q, "session_id": "<from previous response>" if i else None} for i, q in enumerate(reqs)], indent=2))
            (out_dir / f"{name}.json").write_text(json.dumps([slim(r) for _, r in turns], indent=2, default=str))
            (out_dir / f"{name}.md").write_text(to_markdown(name, turns))
            print(name, [r["status"] for _, r in turns])


if __name__ == "__main__":
    main()
