"""Supply-chain delay impact and operational resilience simulation (deterministic + seeded Monte Carlo).

Inputs come from the forecasting engine (demand forecasts, lead-time quantiles, inventory, capacity). Every assumption a result depends
on is returned with it. Nothing here is generated by a language model.
"""

from __future__ import annotations

import hashlib
from typing import Any

import numpy as np

from app.global_intel.forecast import HORIZONS_DAYS, LABOR_RATE, MC_DRAWS, Engine

OVERTIME_PREMIUM = 1.5
BASELINE_COMMITTED = 0.6  # share of hangar capacity committed to scheduled checks (assumption)
WEEKS = 13


def _seed(*parts: str) -> int:
    return int(hashlib.sha256("|".join(parts).encode()).hexdigest()[:8], 16)


def inventory_paths(e: Engine, fid: str, cid: str, supplier_delay: dict[str, float] | None = None, demand_mult: float = 1.0,
                    extra_stock: int = 0, reroute_to: str | None = None) -> dict[int, dict[str, float]]:
    """Same random stream for every variant (seed depends only on facility and category), so differences come from the scenario."""
    return e.inventory_sim(fid, cid, supplier_delay, demand_mult, extra_stock, reroute_to)


def delay_impact(e: Engine, supplier_id: str, delay_days: float, horizon: int = 90) -> dict[str, Any]:
    if supplier_id not in e.sup:
        raise KeyError(supplier_id)
    horizon = min(HORIZONS_DAYS, key=lambda d: abs(d - horizon))
    affected = [lk for lk in e.links if lk["supplier_id"] == supplier_id]
    hubs = sorted({f for (f, _c) in e.demand_fc})
    rows, totals = [], {"baseline": 0.0, "delay": 0.0, "alternate": 0.0, "transfer": 0.0}
    for lk in affected:
        cid = lk["category_id"]
        alts = [x["supplier_id"] for x in e.links if x["category_id"] == cid and x["supplier_id"] != supplier_id]
        alt = min(alts, key=lambda s: e.sup[s]["reliability"]) if alts else None
        for fid in hubs:
            if (fid, cid) not in e.inventory:
                continue
            base = inventory_paths(e, fid, cid)
            dly = inventory_paths(e, fid, cid, {supplier_id: delay_days})
            alt_r = inventory_paths(e, fid, cid, {supplier_id: delay_days}, reroute_to=alt) if alt else dly
            region = e.fac[fid]["region"]
            wh = "F06" if region in ("North America", "Latin America") else "F08" if region in ("Asia-Pacific", "Middle East") else None
            # warehouses are not demand points: read their stock directly
            spare = _warehouse_stock(e, wh, cid) if wh else 0
            trf = inventory_paths(e, fid, cid, {supplier_id: delay_days}, extra_stock=min(spare, 2)) if spare else dly
            hrs = e.cat[cid]["labor_hours"]
            row = {"facility_id": fid, "facility": e.fac[fid]["name"], "region": region, "category_id": cid, "category": e.cat[cid]["name"],
                   "lat": e.fac[fid]["lat"], "lon": e.fac[fid]["lon"], "supply_share": lk["share"], "alternate_supplier": alt,
                   "transfer_from": wh if spare else None,
                   "stockout_baseline": base[horizon]["stockout_prob"], "stockout_delay": dly[horizon]["stockout_prob"],
                   "stockout_alternate": alt_r[horizon]["stockout_prob"], "stockout_transfer": trf[horizon]["stockout_prob"],
                   "backorders_baseline": base[horizon]["expected_backorders"], "backorders_delay": dly[horizon]["expected_backorders"],
                   "deferred_hours_delay": round((dly[horizon]["expected_backorders"] - base[horizon]["expected_backorders"]) * hrs, 2),
                   "curve_baseline": {d: base[d]["p50"] for d in HORIZONS_DAYS}, "curve_delay": {d: dly[d]["p50"] for d in HORIZONS_DAYS}}
            rows.append(row)
            for key, src in (("baseline", base), ("delay", dly), ("alternate", alt_r), ("transfer", trf)):
                totals[key] += src[horizon]["expected_backorders"] * hrs
    rows.sort(key=lambda r: -(r["stockout_delay"] - r["stockout_baseline"]))
    return {
        "supplier": {k: e.sup[supplier_id][k] for k in ("id", "name", "region", "lat", "lon")}, "delay_days": delay_days, "horizon_days": horizon,
        "affected_categories": [{"category_id": lk["category_id"], "category": e.cat[lk["category_id"]]["name"], "share": lk["share"]} for lk in affected],
        "rows": rows,
        "scenarios": [{"scenario": k, "deferred_maintenance_hours": round(v, 1), "cost_usd": round(v * LABOR_RATE * OVERTIME_PREMIUM, 0)}
                      for k, v in totals.items()],
        "worst": rows[:8],
        "assumptions": [
            f"Open orders from {e.sup[supplier_id]['name']} arrive {delay_days:g} days later than their predicted lead time.",
            "Each expected backorder defers one removal-and-replace job by its category labour hours.",
            f"Deferred work is recovered at overtime: USD {LABOR_RATE:.0f}/h x {OVERTIME_PREMIUM}.",
            "Alternate sourcing: open orders re-placed with the most reliable other qualified supplier at its promised lead time.",
            "Stock transfer: up to 2 units from the regional warehouse (Phoenix for the Americas, Singapore for Asia-Pacific/Middle East).",
            f"{MC_DRAWS} seeded Monte Carlo paths; identical random streams across variants.",
        ],
    }


def _warehouse_stock(e: Engine, wh: str, cid: str) -> int:
    from app.core import db

    r = db.query_one("SELECT on_hand FROM g_inventory WHERE facility_id = ? AND category_id = ?", (wh, cid))
    return int(r["on_hand"]) if r else 0


SCENARIOS = {
    "facility_outage": {"label": "Manufacturing / MRO facility outage", "defaults": {"facility_id": "F01", "capacity_cut": 0.6, "start_week": 1, "duration_weeks": 3}},
    "logistics_interruption": {"label": "Logistics interruption", "defaults": {"region": "Asia-Pacific", "added_days": 14, "start_week": 0, "duration_weeks": 4}},
    "supplier_delay": {"label": "Supplier production delay", "defaults": {"supplier_id": "S1", "added_days": 14, "start_week": 0, "duration_weeks": 4}},
    "severe_weather": {"label": "Severe weather disruption", "defaults": {"facility_id": "F04", "capacity_cut": 0.35, "start_week": 2, "duration_weeks": 1}},
    "workforce_shortage": {"label": "Maintenance workforce shortage", "defaults": {"facility_id": "F10", "capacity_cut": 0.3, "start_week": 1, "duration_weeks": 6}},
    "demand_surge": {"label": "Unexpected component demand increase", "defaults": {"category_id": "brake_assembly", "multiplier": 1.8, "start_week": 0, "duration_weeks": 6}},
    "repair_tat_extension": {"label": "Extended repair turnaround", "defaults": {"multiplier": 1.6, "start_week": 0, "duration_weeks": 8}},
    "software_outage": {"label": "Enterprise software outage (manual fallback)", "defaults": {"efficiency": 0.7, "added_days": 3, "start_week": 1, "duration_weeks": 1}},
}


def resilience(e: Engine, scenario: str, params: dict[str, Any], mitigation: dict[str, Any] | None = None) -> dict[str, Any]:
    if scenario not in SCENARIOS:
        raise KeyError(scenario)
    p = {**SCENARIOS[scenario]["defaults"], **{k: v for k, v in params.items() if v is not None}}
    mit = {"overtime_capacity": 0.15, "delay_reduction": 0.5, "demand_deferral": 0.1, **(mitigation or {})}
    hubs = sorted({f for (f, _c) in e.demand_fc})
    start, dur = int(p.get("start_week", 0)), int(p.get("duration_weeks", 1))
    active = [start <= w < start + dur for w in range(WEEKS)]

    def run(disrupt: bool, mitigate: bool, seed: int) -> dict[str, np.ndarray]:
        rng = np.random.default_rng(seed)
        draws = 200
        backlog = np.zeros((draws, WEEKS))
        avail = np.zeros(WEEKS)
        cost = np.zeros(draws)
        b = np.zeros((draws, len(hubs)))
        for w in range(WEEKS):
            for j, fid in enumerate(hubs):
                cap = e.crew_hours[fid]
                lam_hours = 0.0
                for (f, cid), fc in e.demand_fc.items():
                    if f != fid:
                        continue
                    weekly = fc[90][1] / 13
                    mult = 1.0
                    if disrupt and active[w] and scenario == "demand_surge" and cid == p["category_id"]:
                        mult = float(p["multiplier"])
                    if disrupt and active[w] and scenario == "repair_tat_extension":
                        mult = 1 + (float(p["multiplier"]) - 1) * 0.25  # longer TAT -> more serviceable shortfalls -> more swaps
                    lam_hours += weekly * mult * e.cat[cid]["labor_hours"]
                if disrupt and active[w]:
                    if scenario in ("facility_outage", "severe_weather", "workforce_shortage") and p.get("facility_id") == fid:
                        cap *= 1 - float(p["capacity_cut"])
                    if scenario == "software_outage":
                        cap *= float(p["efficiency"])
                if disrupt and mitigate and active[w]:
                    cap *= 1 + mit["overtime_capacity"]
                    lam_hours *= 1 - mit["demand_deferral"]
                demand = rng.poisson(lam_hours / 6, draws) * 6.0  # jobs of ~6 h on average (stated assumption)
                b[:, j] = np.maximum(0, b[:, j] + demand - cap)
                over = np.maximum(0, demand - cap)
                cost += over * LABOR_RATE * (OVERTIME_PREMIUM if mitigate else 1.0)
            backlog[:, w] = b.sum(axis=1)
        # inventory availability at 90 days with the scenario's lead-time effects
        delays: dict[str, float] = {}
        if disrupt:
            if scenario == "supplier_delay":
                delays[p["supplier_id"]] = float(p["added_days"]) * (1 - (mit["delay_reduction"] if mitigate else 0))
            if scenario in ("logistics_interruption", "software_outage"):
                for sid, s in e.sup.items():
                    if scenario == "software_outage" or s["region"] == p.get("region"):
                        delays[sid] = float(p["added_days"]) * (1 - (mit["delay_reduction"] if mitigate else 0))
        surge = float(p["multiplier"]) if disrupt and scenario == "demand_surge" else 1.0
        stock = []
        for (fid, cid) in e.inventory:
            if fid not in hubs:
                continue
            dm = surge if cid == p.get("category_id") else 1.0
            stock.append(inventory_paths(e, fid, cid, delays or None, demand_mult=dm))
        for i, d in enumerate([7, 14, 30, 60, 90]):
            avail_val = float(np.mean([1 - s[d]["stockout_prob"] for s in stock])) if stock else 1.0
            avail[i] = avail_val
        return {"backlog": backlog, "avail": avail[:5], "cost": cost}

    seed = _seed(scenario, str(sorted(p.items())))
    base, dis, rec = run(False, False, seed), run(True, False, seed), run(True, True, seed)

    def summary(r: dict[str, np.ndarray]) -> dict[str, Any]:
        med = np.median(r["backlog"], axis=0)
        return {"backlog_p50": [round(float(x), 1) for x in med], "backlog_p10": [round(float(x), 1) for x in np.quantile(r["backlog"], 0.1, axis=0)],
                "backlog_p90": [round(float(x), 1) for x in np.quantile(r["backlog"], 0.9, axis=0)],
                "peak_backlog_hours": round(float(med.max()), 1),
                "inventory_availability": {str(d): round(float(v), 4) for d, v in zip(HORIZONS_DAYS, r["avail"], strict=True)},
                "cost_p50_usd": round(float(np.median(r["cost"])), 0), "cost_p90_usd": round(float(np.quantile(r["cost"], 0.9)), 0)}

    out = {"baseline": summary(base), "disruption": summary(dis), "recovery": summary(rec)}
    for k in ("disruption", "recovery"):
        med, b = np.array(out[k]["backlog_p50"]), np.array(out["baseline"]["backlog_p50"])
        end = start + dur
        rec_week = next((w for w in range(end, WEEKS) if med[w] <= b[w] * 1.05 + 1), None)
        out[k]["recovery_weeks_after_disruption"] = (rec_week - end) if rec_week is not None else None
        out[k]["recovered_within_horizon"] = rec_week is not None
    return {"scenario": scenario, "label": SCENARIOS[scenario]["label"], "params": p, "mitigation": mit, "weeks": list(range(1, WEEKS + 1)),
            "results": out,
            "assumptions": [
                "Each hub's unscheduled-work crew = 125% of its average historical weekly removal hours.",
                "Unscheduled work arrives as Poisson jobs of ~6 labour hours from the 90-day demand forecast; 200 seeded paths.",
                "Backlog carries over week to week; recovery = first week after the disruption when backlog is within 5% of baseline.",
                f"Mitigation (recovery scenario): +{int(mit['overtime_capacity'] * 100)}% overtime capacity, "
                f"{int(mit['delay_reduction'] * 100)}% shorter added lead time (expediting), {int(mit['demand_deferral'] * 100)}% of deferrable work deferred.",
                f"Cost = hours above capacity x USD {LABOR_RATE:.0f}/h (x {OVERTIME_PREMIUM} with overtime). Synthetic, not a budget.",
            ]}
