CREATE VIEW V_PART_AVAILABILITY AS
  SELECT P.PART_NO, P.PART_DESC, S.BASE_CODE, S.QTY_OH, S.LOT_NO, S.LAST_CNT_DT
  FROM MRO_PART_MASTER P JOIN MRO_STOCK_LOC S ON S.PART_NO = P.PART_NO;
