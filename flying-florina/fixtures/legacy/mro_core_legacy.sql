CREATE TABLE MRO_AIRCRAFT (
  AC_ID        VARCHAR2(10) PRIMARY KEY,
  AC_TYPE      VARCHAR2(40) NOT NULL,
  BASE_CODE    VARCHAR2(12),
  IN_SVC_DT    DATE,
  FLT_HRS      NUMBER(9,1),
  CYCLES       NUMBER(9)
);

CREATE TABLE MRO_PART_MASTER (
  PART_NO      VARCHAR2(20) PRIMARY KEY,
  PART_DESC    VARCHAR2(200),
  ATA_CHAP     VARCHAR2(4),
  UNIT_COST    NUMBER(12,2),
  CRIT_CODE    CHAR(1),
  SUPPLIER_CD  VARCHAR2(10)
);

CREATE TABLE MRO_STOCK_LOC (
  LOC_ID       NUMBER(10) PRIMARY KEY,
  PART_NO      VARCHAR2(20) NOT NULL REFERENCES MRO_PART_MASTER(PART_NO),
  BASE_CODE    VARCHAR2(12),
  QTY_OH       NUMBER(6),
  LOT_NO       VARCHAR2(20),
  LAST_CNT_DT  DATE
);

CREATE TABLE MRO_WORK_ORDER (
  WO_NO        VARCHAR2(12) PRIMARY KEY,
  AC_ID        VARCHAR2(10) NOT NULL,
  STATUS_CD    CHAR(2),
  OPEN_DT      DATE,
  CLOSE_DT     DATE,
  WO_TEXT      VARCHAR2(4000),
  TECH_ID      VARCHAR2(10),
  CONSTRAINT FK_WO_AC FOREIGN KEY (AC_ID) REFERENCES MRO_AIRCRAFT(AC_ID)
);

CREATE TABLE MRO_WO_PART (
  WO_NO        VARCHAR2(12) NOT NULL,
  PART_NO      VARCHAR2(20) NOT NULL,
  QTY_REQ      NUMBER(6),
  CONSTRAINT FK_WOP_WO FOREIGN KEY (WO_NO) REFERENCES MRO_WORK_ORDER(WO_NO),
  CONSTRAINT FK_WOP_PART FOREIGN KEY (PART_NO) REFERENCES MRO_PART_MASTER(PART_NO)
);

CREATE TABLE MRO_TECH (
  TECH_ID      VARCHAR2(10) PRIMARY KEY,
  TECH_NAME    VARCHAR2(80),
  BASE_CODE    VARCHAR2(12),
